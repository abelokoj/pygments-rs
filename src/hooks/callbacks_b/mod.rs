    // cleared before each case).

    fn check(alias: &str, text: &str, expected: &[(&str, &str)]) {
        let lexer = crate::lexer_by_name(alias).expect("lexer");
        let got: Vec<(&str, &str)> = lexer.tokenize(text).map(|(t, v)| (t.short_path(), v)).collect();
        assert_eq!(got, expected);
    }

